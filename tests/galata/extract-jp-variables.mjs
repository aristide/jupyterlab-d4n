#!/usr/bin/env node
/**
 * Produce `mapping/jp-variables.manifest.json` — the list of every `--jp-*`
 * custom property the TARGET JupyterLab build actually defines.
 *
 * This closes PRD AC5 ("every --jp-* variable consumed by JupyterLab core has a
 * mapping entry with a written rationale"). Until the manifest exists,
 * `packages/tokens/build.mjs` can only warn that adapter completeness is
 * unverified; once it exists, an unmapped variable FAILS the build with a list.
 *
 * It is a separate script rather than a hand-maintained list on purpose: the
 * set changes on every JupyterLab minor, and a hand-maintained list silently
 * rots into a false pass. Appendix C step 3 of the upgrade playbook re-runs it.
 *
 *   docker compose up -d
 *   node tests/galata/extract-jp-variables.mjs
 *   node tests/galata/extract-jp-variables.mjs --url http://localhost:8890
 *
 * TODO P0-03.
 */
import { writeFileSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = dirname(dirname(dirname(fileURLToPath(import.meta.url))));
const OUT = join(REPO, 'mapping', 'jp-variables.manifest.json');

const argUrl = process.argv.indexOf('--url');
const BASE =
  argUrl !== -1
    ? process.argv[argUrl + 1]
    : (process.env.JUPYTER_URL ?? 'http://localhost:8890');

let chromium;
try {
  ({ chromium } = await import('@playwright/test'));
} catch {
  console.error(
    'Playwright is not installed. Run `jlpm install` first (@playwright/test is\n' +
      'a devDependency), then `npx playwright install chromium`.'
  );
  process.exit(1);
}

console.log(`Extracting --jp-* variables from ${BASE}/lab ...`);

const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 720 } });

try {
  await page.goto(`${BASE}/lab`, { waitUntil: 'networkidle', timeout: 60_000 });
  // The shell has to have rendered, or core's stylesheets are not all attached.
  await page.waitForSelector('#main', { timeout: 60_000 });

  const result = await page.evaluate(() => {
    const defined = new Set();
    const referenced = new Set();

    const scanText = text => {
      for (const m of text.matchAll(/var\(\s*(--jp-[A-Za-z0-9-]+)/g)) {
        referenced.add(m[1]);
      }
    };

    const scanRule = rule => {
      // Nested rules (media queries, supports) carry their own cssRules.
      if (rule.cssRules) {
        for (const nested of rule.cssRules) {
          scanRule(nested);
        }
      }
      if (!rule.style) {
        return;
      }
      for (let i = 0; i < rule.style.length; i += 1) {
        const prop = rule.style[i];
        if (prop.startsWith('--jp-')) {
          defined.add(prop);
        }
      }
      if (rule.cssText) {
        scanText(rule.cssText);
      }
    };

    for (const sheet of document.styleSheets) {
      let rules;
      try {
        rules = sheet.cssRules;
      } catch {
        // Cross-origin stylesheet — not ours, and not something we can map.
        continue;
      }
      for (const rule of rules) {
        scanRule(rule);
      }
    }

    return {
      defined: [...defined].sort(),
      referenced: [...referenced].sort()
    };
  });

  // A variable core REFERENCES but never DEFINES still matters: it is a hook
  // core expects a theme to fill, and leaving it unmapped means core falls back
  // to its own default mid-interface.
  const all = [...new Set([...result.defined, ...result.referenced])]
    .filter(v => !v.startsWith('--jp-private-'))
    .sort();

  const jupyterlabVersion = await page.evaluate(() =>
    document.getElementById('jupyter-config-data')
      ? JSON.parse(document.getElementById('jupyter-config-data').textContent)
          .appVersion
      : 'unknown'
  );

  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(
    OUT,
    JSON.stringify(
      {
        $comment:
          'GENERATED by tests/galata/extract-jp-variables.mjs. Re-run against each ' +
          'target JupyterLab (upgrade playbook step 3). packages/tokens/build.mjs ' +
          'fails if any entry here is missing from mapping/jp-adapter.yaml.',
        jupyterlabVersion,
        extractedFrom: `${BASE}/lab`,
        counts: {
          defined: result.defined.length,
          referencedOnly: all.length - result.defined.length,
          total: all.length
        },
        variables: all
      },
      null,
      2
    ) + '\n'
  );

  console.log(
    `JupyterLab ${jupyterlabVersion}: ${result.defined.length} defined, ` +
      `${all.length} total (excluding --jp-private-*).`
  );
  console.log(`Wrote ${OUT}`);
  console.log(
    '\nNow run `jlpm build:tokens` — completeness checking is active.'
  );
} finally {
  await browser.close();
}
